def main_characters():
    names_txt = (MOD / "common" / "names" / "ante_names.txt").read_text(encoding="utf-8-sig")
    port_txt = (MOD / "portraits" / "00_portraits.txt").read_text(encoding="utf-8-sig")
    out_dir = MOD / "gfx" / "leaders" / "ante" / "advisors"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.dds"):
        old.unlink()
    sprites = ["# Generated by tools/government.py - small portraits of counsellors and the war council (own art, CC0)",
               "spriteTypes = {"]
    made_styles = {}

    def generic_pic(style, n):
        key = f"{style}_{n}"
        if key not in made_styles:
            small_portrait(style, False, PT.seed_of(f"adv_{key}")).save(out_dir / f"{key}.dds")
            sprites.append(f'\tspriteType = {{ name = "GFX_ante_adv_{key}" '
                           f'texturefile = "gfx/leaders/ante/advisors/{key}.dds" }}')
            made_styles[key] = True
        return f"GFX_ante_adv_{key}"

    chars, loc = ["# Generated by tools/government.py from tools/data/advisors_509bc.py", "characters = {"], ["l_english:"]
    named = {}
    for tag, key, name, slot, trait, female, desc in NAMED:
        assert trait in TRAITS, trait
        named.setdefault(tag, []).append((key, name, slot, trait, female, desc))
    totals = {"political_advisor": 0, "army_chief": 0, "navy_chief": 0, "high_command": 0}
    for fp in sorted((MOD / "history" / "countries").glob("*.txt")):
        tag = fp.name[:3]
        if tag == "WLD":
            continue
        rnd = random.Random(int(hashlib.md5(f"adv{tag}".encode()).hexdigest()[:8], 16))
        pb = block(port_txt, tag)
        m = re.search(r'"GFX_ante_portrait_(\w+?)_male_\d+"', pb)
        style = m.group(1) if m else "greek"
        style = {"roman": "roman"}.get(style, style)
        nb = block(names_txt, tag)
        mm = re.search(r"\bmale = \{\s*names = \{([^}]*)\}", nb)
        male = words(mm.group(1)) if mm else []
        sm = re.search(r"surnames = \{([^}]*)\}", nb)
        surnames = words(sm.group(1)) if sm else []
        div = count(MOD / "history" / "units" / f"{tag}_245.txt", r"^\s*division = \{")
        ships = count(MOD / "history" / "units" / f"{tag}_245_naval.txt", r"\bship = \{")
        want = {"political_advisor": 3, "army_chief": 1 if div else 0, "navy_chief": 1 if ships >= 2 else 0,
                "high_command": 0 if div < 4 else (1 if div < 10 else 2)}
        people = []
        for key, name, slot, trait, female, desc in named.get(tag, []):
            st = "greek" if key in GREEKS_ABROAD else ("spartan" if tag == "LAK" else style)
            pic = f"GFX_ante_adv_{tag}_{key}"
            small_portrait(st, female, PT.seed_of(f"{tag}_{key}")).save(out_dir / f"{tag}_{key}.dds")
            sprites.append(f'\tspriteType = {{ name = "{pic}" texturefile = "gfx/leaders/ante/advisors/{tag}_{key}.dds" }}')
            people.append((key, name, slot, trait, desc, pic))
            want[slot] = max(0, want[slot] - 1)
        used_names = {p[1] for p in people}
        used_traits = {p[3] for p in people}
        civil = style in CITY_STYLES
        pools = {"political_advisor": CIVIL_POOL if civil else
                 ([t if t != "ante_adv_high_priest" else "ante_adv_druid" for t in TRIBAL_POOL] if style == "celtic"
                  else TRIBAL_POOL),
                 "army_chief": ARMY_POOL, "navy_chief": NAVY_POOL, "high_command": HC_POOL}
        n = 0
        for slot, k in want.items():
            for _ in range(k):
                pool = [t for t in pools[slot] if t not in used_traits] or pools[slot]
                trait = rnd.choice(pool)
                used_traits.add(trait)
                for _try in range(40):
                    name = rnd.choice(male) if male else f"{tag} counsellor"
                    if surnames and rnd.random() < 0.6:
                        name += " " + rnd.choice(surnames)
                    if name not in used_names:
                        break
                used_names.add(name)
                n += 1
                people.append((f"g{n}", name, slot, trait, "", generic_pic(style, rnd.randrange(6))))
        lines = []
        for key, name, slot, trait, desc, pic in people:
            cid = f"{tag}_adv_{key}"
            ledger = {"army_chief": "army", "navy_chief": "navy", "high_command": "army"}.get(slot)
            cost = 150 if slot == "political_advisor" else 100
            b = [f"\t{cid} = {{", f"\t\tname = {cid}",
                 f'\t\tportraits = {{ civilian = {{ small = "{pic}" }} army = {{ small = "{pic}" }} }}',
                 "\t\tadvisor = {", f"\t\t\tslot = {slot}", f"\t\t\tidea_token = {cid}"]
            if ledger:
                b.append(f"\t\t\tledger = {ledger}")
            b += ["\t\t\tallowed = { original_tag = " + tag + " }", f"\t\t\ttraits = {{ {trait} }}", f"\t\t\tcost = {cost}",
                  "\t\t\tai_will_do = { factor = 1 }", "\t\t}", "\t}"]
            chars += b
            loc.append(f' {cid}:0 "{name}"')
            if desc:
                loc.append(f' {cid}_desc:0 "{desc}"')
            lines.append(f"recruit_character = {cid}")
            totals[slot] += 1
        text = fp.read_text(encoding="utf-8-sig").split("\n" + MARK)[0].rstrip("\n")
        fp.write_text(text + "\n" + MARK + "\n" + "\n".join(lines) + "\n", encoding="utf-8-sig", newline="\n")
    chars.append("}")
    sprites.append("}")
    (MOD / "common" / "characters" / "ante_advisors.txt").write_text("\n".join(chars) + "\n", encoding="utf-8", newline="\n")
    (MOD / "interface" / "ante_advisors.gfx").write_text("\n".join(sprites) + "\n", encoding="utf-8", newline="\n")
    for key, (name, group, mods) in TRAITS.items():
        loc.append(f' {key}:0 "{name}"')
    (MOD / "localisation" / "english" / "ante_advisors_l_english.yml").write_text("\n".join(loc) + "\n",
                                                                                  encoding="utf-8-sig", newline="\n")
    tr = ["# Generated by tools/government.py - traits of the counsellors and the war council", "leader_traits = {"]
    for key, (name, group, mods) in TRAITS.items():
        tr += [f"\t{key} = {{", "\t\trandom = no"] + [f"\t\t{k} = {v}" for k, v in mods.items()] + \
              ["\t\tai_will_do = { factor = 1 }", "\t}"]
    tr.append("}")
    (MOD / "common" / "country_leader" / "ante_advisor_traits.txt").write_text("\n".join(tr) + "\n", encoding="utf-8",
                                                                                newline="\n")
    return totals


