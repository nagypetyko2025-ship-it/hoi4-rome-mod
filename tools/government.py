BRONZE, DARK = (212, 170, 96), (34, 30, 26)


def badge(glyph_kind, size, level=None, colour=BRONZE, plus=False):
    """a round dark badge with a bronze ring, the shaded glyph and level pips"""
    S = 4
    W = size[0] * S
    im = Image.new("RGBA", (W, size[1] * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    m = 2 * S
    d.ellipse((m, m, W - m, size[1] * S - m), fill=(110, 84, 50, 255))
    d.ellipse((m + 3 * S, m + 3 * S, W - m - 3 * S, size[1] * S - m - 3 * S), fill=DARK + (255,))
    im = im.resize(size, Image.LANCZOS)
    g = shaded(glyph(glyph_kind, int(size[0] * 0.62), int(size[1] * 0.55)), colour)
    im.alpha_composite(g, ((size[0] - g.width) // 2, int(size[1] * 0.16)))
    d = ImageDraw.Draw(im)
    if level is not None:
        n = max(level, 0)
        for i in range(5):
            x = size[0] // 2 - 12 + i * 6
            y = int(size[1] * 0.78)
            d.ellipse((x - 2, y - 2, x + 2, y + 2), fill=(230, 200, 120, 255) if i < n else (70, 60, 50, 255))
    if plus:
        cx, cy = int(size[0] * 0.74), int(size[1] * 0.26)
        d.rectangle((cx - 7, cy - 2, cx + 7, cy + 2), fill=(70, 200, 70, 255))
        d.rectangle((cx - 2, cy - 7, cx + 2, cy + 7), fill=(70, 200, 70, 255))
    return im


