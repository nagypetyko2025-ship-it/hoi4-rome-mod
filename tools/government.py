def glyph(kind, w, h):
    """tech.py draws its glyphs on a 61 x 54 sheet: draw there, then scale (keeping the shape) into w x h"""
    g = _glyph(kind)
    f = min(w / g.width, h / g.height)
    g = g.resize((max(1, int(g.width * f)), max(1, int(g.height * f))), Image.LANCZOS)
    out = Image.new("L", (w, h), 0)
    out.paste(g, ((w - g.width) // 2, (h - g.height) // 2))
    return out

