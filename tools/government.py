# ---------------------------------------------------------------- helpers shared with commanders.py
def block(text, tag):
    m = re.search(rf"^{tag} = \{{", text, re.M)
    if not m:
        return ""
    depth, i = 0, m.end() - 1
    for j in range(i, len(text)):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        if depth == 0:
            return text[i:j]
    return ""


def words(text):
    return re.findall(r"[^\s{}\"]+", text)


def count(path, pat):
    return len(re.findall(pat, path.read_text(encoding="utf-8-sig"), re.M)) if path.exists() else 0


def small_portrait(style, female, seed):
    """the painted bust of portraits.py, cut to the head and shoulders of a 65 x 67 advisor picture"""
    im = PT.portrait(style, female, seed).convert("RGBA")
    return im.crop((12, 8, 144, 144)).resize(SMALL, Image.LANCZOS)


