"""Buildings of the ancient world (reads the game's common/buildings once, like tools/army.py).

The base game's buildings keep their keys (the engine and the base game's scripts need them):
  - the ones with an ancient counterpart are renamed (localisation/english/replace/ante_buildings_l_english.yml):
    workshops, armouries, shipyards, harbours, roads, forts, sea walls
  - the modern ones are switched off: a copy of the game's 00_buildings.txt in the mod where they get
    dlc_allowed = { always = no } (the same mechanism that hides a building of a DLC you do not own).
Run whenever the game updates. Building icons are still the base game's (next step).
"""
import re
import sys
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

REMOVED = ["air_base", "anti_air_building", "synthetic_refinery", "fuel_silo", "radar_station", "rocket_site",
           "naval_supply_hub", "naval_headquarters", "mega_gun_emplacement", "nuclear_reactor",
           "nuclear_reactor_heavy_water", "commercial_nuclear_reactor"]

NAMES = {   # key: (name, plural, description)
    "industrial_complex": ("Workshops", "Workshops",
                           "Potters, weavers, carpenters, masons and traders: the work of a town. They produce the goods people "
                           "need and build everything else - walls, roads, harbours, temples."),
    "arms_factory": ("Armoury", "Armouries",
                     "Smiths and armourers forge spearheads, swords, helmets and shields, and make bows and wagons for the army."),
    "dockyard": ("Shipyard", "Shipyards", "Slipways, timber stores and shipwrights: here penteconters and triremes are built."),
    "naval_base": ("Harbour", "Harbours",
                   "Moles, quays and ship sheds. The fleet rests, refits and takes on water here; goods and soldiers sail from "
                   "here overseas. The larger the harbour, the more ships it can serve."),
    "infrastructure": ("Roads", "Roads",
                       "Tracks, causeways, bridges and fords. Better roads carry more grain and move armies faster."),
    "bunker": ("Fortifications", "Fortifications",
               "Ramparts, ditches and walls: every level makes an attacker pay $VALUE|+%0$ more in battle."),
    "coastal_bunker": ("Sea Walls", "Sea Walls",
                       "Walls and towers along the shore: every level makes an enemy landing pay $VALUE|+%0$ more."),
}


def find_game():
    try:
        from test_paths import game_dir  # optional helper
        return Path(game_dir())
    except Exception:
        pass
    p = MOD.parent.parent
    if (p / "common" / "buildings" / "00_buildings.txt").exists():
        return p
    sys.exit("game folder not found (the mod must lie in <game>/mod/)")


def main():
    game = find_game()
    src = (game / "common" / "buildings" / "00_buildings.txt").read_text(encoding="utf-8-sig")
    lines = src.split("\n")
    out, current, done = [], None, set()
    for line in lines:
        m = re.match(r"^\t([a-z_]+) = \{", line)
        if m:
            current = m.group(1) if m.group(1) in REMOVED else None
            out.append(line)
            if current:
                out.append("\t\tdlc_allowed = { always = no }   # Ante Imperium: not in the ancient world")
                done.add(current)
            continue
        if current and re.match(r"^\t\tdlc_allowed\s*=", line):
            continue                                   # the base game's own DLC condition is replaced
        out.append(line)
    missing = set(REMOVED) - done
    assert not missing, f"not in the game's buildings: {missing}"
    head = ("# Generated by tools/buildings.py from the game's common/buildings/00_buildings.txt:\n"
            "# modern buildings switched off with dlc_allowed = { always = no }: " + " ".join(REMOVED) + "\n")
    p = MOD / "common" / "buildings" / "00_buildings.txt"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(head + "\n".join(out), encoding="utf-8", newline="\n")
    loc = ["l_english:"]
    for key, (name, plural, desc) in NAMES.items():
        loc += [f' {key}:0 "{name}"', f' {key}_plural:0 "{plural}"', f' {key}_desc:0 "{desc}"']
    q = MOD / "localisation" / "english" / "replace" / "ante_buildings_l_english.yml"
    q.parent.mkdir(parents=True, exist_ok=True)
    q.write_text("\n".join(loc) + "\n", encoding="utf-8-sig", newline="\n")
    print(f"written: {len(REMOVED)} modern buildings switched off, {len(NAMES)} renamed")


if __name__ == "__main__":
    main()
