"""Buildings of the ancient world (reads the game's common/buildings once, like tools/army.py).

The base game's buildings keep their keys (the engine and the base game's scripts need them):
  - the ones with an ancient counterpart are renamed (localisation/english/replace/ante_buildings_l_english.yml):
    workshops, armouries, shipyards, harbours, roads, forts, sea walls
  - the modern ones are switched off: a copy of the game's 00_buildings.txt in the mod where they get
    dlc_allowed = { always = no } (the same mechanism that hides a building of a DLC you do not own).
Run whenever the game updates. Also writes the farm (ante_farm, grain) and the building icon strip (own art).
"""
import re
import sys
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

REMOVED = ["air_base", "anti_air_building", "synthetic_refinery", "fuel_silo", "radar_station", "rocket_site",
           "naval_supply_hub", "naval_headquarters", "mega_gun_emplacement", "nuclear_reactor",
           "nuclear_reactor_heavy_water", "commercial_nuclear_reactor"]

NAMES = {   # key: (name, plural, description)
    "industrial_complex": ("Workshops", "Workshops",
                           "Potters, weavers, carpenters, masons and traders: the work of a town. They produce the goods people "
                           "need and build everything else - walls, roads, harbours, temples."),
    "arms_factory": ("Armoury", "Armouries",
                     "Smiths and armourers forge spearheads, swords, helmets and shields, and make bows and wagons for the army."),
    "dockyard": ("Shipyard", "Shipyards", "Slipways, timber stores and shipwrights: here penteconters and triremes are built."),
    "naval_base": ("Harbour", "Harbours",
                   "Moles, quays and ship sheds. The fleet rests, refits and takes on water here; goods and soldiers sail from "
                   "here overseas. The larger the harbour, the more ships it can serve."),
    "infrastructure": ("Roads", "Roads",
                       "Tracks, causeways, bridges and fords. Better roads carry more grain and move armies faster."),
    "bunker": ("Fortifications", "Fortifications",
               "Ramparts, ditches and walls: every level makes an attacker pay $VALUE|+%0$ more in battle."),
    "coastal_bunker": ("Sea Walls", "Sea Walls",
                       "Walls and towers along the shore: every level makes an enemy landing pay $VALUE|+%0$ more."),
}


def find_game():
    try:
        from test_paths import game_dir  # optional helper
        return Path(game_dir())
    except Exception:
        pass
    p = MOD.parent.parent
    if (p / "common" / "buildings" / "00_buildings.txt").exists():
        return p
    try:
        from mapdata import GAME  # finds the game on any drive (HOI4_DIR overrides), like tools/army.py
        if (Path(GAME) / "common" / "buildings" / "00_buildings.txt").exists():
            return Path(GAME)
    except Exception:
        pass
    sys.exit("game folder not found (the mod must lie in <game>/mod/)")


def main():
    game = find_game()
    src = (game / "common" / "buildings" / "00_buildings.txt").read_text(encoding="utf-8-sig")
    lines = src.split("\n")
    out, current, done, block = [], None, set(), None
    for line in lines:
        m = re.match(r"^\t([a-z_]+) = \{", line)
        if m:
            block = m.group(1)
        # roads: 10 levels instead of 5 (each worth half as much: common/defines/zz_ante_imperium.lua, world.py
        # doubles the levels of the start) - round 22
        if block == "infrastructure" and re.match(r"^\t\t\tstate_max\s*=\s*5\s*$", line):
            out.append("\t\t\tstate_max = 10   # Ante Imperium: 10 levels of roads")
            done.add("infrastructure 10")
            continue
        if m:
            current = m.group(1) if m.group(1) in REMOVED else None
            out.append(line)
            if current:
                out.append("\t\tdlc_allowed = { always = no }   # Ante Imperium: not in the ancient world")
                done.add(current)
            continue
        if current and re.match(r"^\t\tdlc_allowed\s*=", line):
            continue                                   # the base game's own DLC condition is replaced
        out.append(line)
    assert "infrastructure 10" in done, "the road level cap was not found"
    missing = set(REMOVED) - done
    assert not missing, f"not in the game's buildings: {missing}"
    head = ("# Generated by tools/buildings.py from the game's common/buildings/00_buildings.txt:\n"
            "# modern buildings switched off with dlc_allowed = { always = no }: " + " ".join(REMOVED) + "\n")
    p = MOD / "common" / "buildings" / "00_buildings.txt"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(head + "\n".join(out), encoding="utf-8", newline="\n")
    loc = ["l_english:"]
    for key, (name, plural, desc) in NAMES.items():
        loc += [f' {key}:0 "{name}"', f' {key}_plural:0 "{plural}"', f' {key}_desc:0 "{desc}"']
    q = MOD / "localisation" / "english" / "replace" / "ante_buildings_l_english.yml"
    q.parent.mkdir(parents=True, exist_ok=True)
    q.write_text("\n".join(loc) + "\n", encoding="utf-8-sig", newline="\n")
    write_farm()
    write_icon_strip()
    print(f"written: {len(REMOVED)} modern buildings switched off, {len(NAMES)} renamed, the farm, the icon strip")


# ---------------------------------------------------------------- the farm (round 26, Peti)
FARM_GRAIN = 4      # grain (the 'coal' resource) per farm; four farming techs add 1 each, up to 8 (tools/data/tech_tree.py)


def write_farm():
    """a new building: fields, granaries and threshing floors that grow grain. It takes the base game's synthetic
    refinery's icon frame (10) - the refinery is switched off - and its way of producing a resource."""
    text = f"""# Generated by tools/buildings.py - the farm: grows grain (the engine's 'coal' resource)
buildings = {{
	ante_farm = {{
		base_cost = 3500
		icon_frame = 10
		local_resources_coal = {FARM_GRAIN}
		value = 2
		infrastructure_construction_effect = yes
		show_modifier = yes
		level_cap = {{
			shares_slots = yes
			state_max = 4
		}}
	}}
}}
"""
    (MOD / "common" / "buildings" / "ante_farm.txt").write_text(text, encoding="utf-8", newline="\n")
    loc = ["l_english:", ' ante_farm:0 "Farm"', ' ante_farm_plural:0 "Farms"',
           f' ante_farm_desc:0 "Fields, granaries and threshing floors: every farm brings in {FARM_GRAIN} grain, more '
           'with better farming (irrigation, the iron ploughshare, crop rotation, agronomy - up to 8). Grain feeds the '
           'workshops."']
    (MOD / "localisation" / "english" / "ante_farm_l_english.yml").write_text("\n".join(loc) + "\n", encoding="utf-8-sig",
                                                                             newline="\n")


# ---------------------------------------------------------------- the building icons, ancient (own art)
STRIP_GLYPHS = {1: "anvil", 2: "sword", 3: "wheel", 4: "ship", 6: "tower", 7: "wall", 8: "wall", 10: "wheat",
                15: "tent", 16: "wheel", 23: "wall", 25: "ship", 26: "wall", 30: "coin", 31: "anvil"}


def write_icon_strip():
    """gfx/interface/buildings/building_icon_strip.dds (31 frames of 46 x 46, the base game's path): a dark tile with
    an orange glyph for every building we use; the frames of switched-off buildings get a plain column"""
    from PIL import Image, ImageDraw
    from tech import glyph, shaded
    n, w = 31, 46
    strip = Image.new("RGBA", (n * w, w), (0, 0, 0, 0))
    for i in range(1, n + 1):
        tile = Image.new("RGBA", (w, w), (0, 0, 0, 0))
        d = ImageDraw.Draw(tile)
        d.rounded_rectangle((1, 1, w - 2, w - 2), 6, fill=(30, 28, 26, 255), outline=(80, 72, 62, 255), width=2)
        g = glyph(STRIP_GLYPHS.get(i, "column"))
        f = min(34 / g.width, 34 / g.height)
        g = g.resize((int(g.width * f), int(g.height * f)), Image.LANCZOS)
        pic = shaded(g, (236, 128, 44))
        tile.alpha_composite(pic, ((w - pic.width) // 2, (w - pic.height) // 2))
        strip.alpha_composite(tile, ((i - 1) * w, 0))
    p = MOD / "gfx" / "interface" / "buildings" / "building_icon_strip.dds"
    p.parent.mkdir(parents=True, exist_ok=True)
    strip.save(p)


if __name__ == "__main__":
    main()
