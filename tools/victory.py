"""Victory screens (round 42, Peti): when Rome, Carthage or Persia reaches its goal, a news window with a triumphant
picture, a short text and two buttons - "We won!" and "We continue!". Shown only to a human player.

  Rome      all of peninsular Italy AND all of Sicily AND all of the Po valley (both, not either - the formable
            decision 'Italia' still needs only one of them); checked every week (WEEKLY, used by content.py)
  Carthage  the decision 'The Punic Empire' (tools/formables.py fires the event)
  Persia    the decision 'King of the Four Corners of the World' (tools/persia_story.py fires the event)

Pictures (tools/data/victory/, cropped to the base game's news picture size 397 x 153):
  rom.jpg  Carle Vernet, The Triumph of Aemilius Paulus (1789), The Metropolitan Museum of Art - CC0
  car.jpg  J. M. W. Turner, Dido building Carthage (1815), National Gallery, London - public domain
  prs.jpg  Apadana Hall, eastern stairway, Persepolis (photograph, 19th c.), The Metropolitan Museum of Art - CC0
Writes events/ante_victory.txt, interface/ante_victory.gfx, gfx/event_pictures/ante_victory_*.dds,
localisation/english/ante_victory_l_english.yml. No game needed, ~1 s; run after formables.py.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

MOD = Path(__file__).resolve().parent.parent
SRC = MOD / "tools" / "data" / "victory"
W, H = 397, 153

VICTORIES = [   # (id, tag, picture, focus point of the crop (0..1 across, 0..1 down), title, text)
    (1, "ROM", "rom.jpg", (0.5, 0.5), "Victory! Italy Is Rome's",
     "We have taken Italy, we have taken the Po, we have taken Sicily! Everything that matters is ours! From here we "
     "can go further and unite the whole world! We have won - we are the strongest!"),
    (2, "CAR", "car.jpg", (0.5, 0.55), "Victory! Mistress of the Western Sea",
     "Africa is ours, the south of Hispania has fallen, and now we bring wealth and prosperity to everyone. Long live "
     "Carthage, long live the leader!"),
    (3, "PRS", "prs.jpg", (0.5, 0.45), "Victory! King of the Four Corners of the World",
     "The Greeks have bowed before us. We are the greatest power in the world: the wealth and prosperity we have "
     "created make us the centre of civilisation! And we held the empire together - we did not fall apart!"),
]


def picture(src, focus):
    im = Image.open(src).convert("RGB")
    scale = max(W / im.width, H / im.height)
    im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
    fx, fy = focus
    x = min(max(0, round(fx * im.width - W / 2)), im.width - W)
    y = min(max(0, round(fy * im.height - H / 2)), im.height - H)
    im = im.crop((x, y, x + W, y + H)).filter(ImageFilter.UnsharpMask(radius=1, percent=60))
    d = ImageDraw.Draw(im)
    d.rectangle((0, 0, W - 1, H - 1), outline=(214, 172, 80), width=2)    # a thin golden frame
    return im.convert("RGBA")


def weekly():
    import formables as FM
    ids = sorted(set(FM.states_of(FM.PENINSULA) + FM.states_of(FM.SICILY) + FM.states_of(FM.PO)))
    held = "\n".join(f"\t\tcontrols_state = {i}" for i in ids)
    return f"""if = {{
	limit = {{
		original_tag = ROM
		is_ai = no
		NOT = {{ has_country_flag = ante_victory_shown }}
{held}
	}}
	set_country_flag = ante_victory_shown
	news_event = {{ id = ante_victory.1 }}
}}"""


FIRE = {tag: ("if = { limit = { is_ai = no NOT = { has_country_flag = ante_victory_shown } } "
              f"set_country_flag = ante_victory_shown news_event = {{ id = ante_victory.{i} days = 1 }} }}")
        for i, tag, *_ in VICTORIES}
WEEKLY = ""


def main():
    out = MOD / "gfx" / "event_pictures"
    out.mkdir(parents=True, exist_ok=True)
    sprites = ["# Generated by tools/victory.py - victory pictures (see the header of the tool for the sources)",
               "spriteTypes = {"]
    events = ["# Generated by tools/victory.py - the victory screens", "add_namespace = ante_victory", ""]
    loc = ["l_english:"]
    for i, tag, pic, focus, title, text in VICTORIES:
        picture(SRC / pic, focus).save(out / f"ante_victory_{tag.lower()}.dds")
        sprites.append(f'\tspriteType = {{ name = "GFX_ante_victory_{tag.lower()}" '
                       f'texturefile = "gfx/event_pictures/ante_victory_{tag.lower()}.dds" }}')
        n = f"ante_victory.{i}"
        events += ["news_event = {", f"\tid = {n}", f"\ttitle = {n}.t", f"\tdesc = {n}.d",
                   f"\tpicture = GFX_ante_victory_{tag.lower()}", "\tis_triggered_only = yes",
                   "\toption = {", f"\t\tname = {n}.a", f'\t\tlog = "ANTE|[GetDateText]|victory|[ROOT.GetTag]|won"', "\t}",
                   "\toption = {", f"\t\tname = {n}.b", f'\t\tlog = "ANTE|[GetDateText]|victory|[ROOT.GetTag]|continue"',
                   "\t}", "}", ""]
        loc += [f' {n}.t:0 "{title}"', f' {n}.d:0 "{text}"', f' {n}.a:0 "We won!"', f' {n}.b:0 "We continue!"']
    sprites.append("}")
    (MOD / "interface" / "ante_victory.gfx").write_text("\n".join(sprites) + "\n", encoding="utf-8", newline="\n")
    (MOD / "events" / "ante_victory.txt").write_text("\n".join(events), encoding="utf-8", newline="\n")
    (MOD / "localisation" / "english" / "ante_victory_l_english.yml").write_text(
        "\n".join(loc) + "\n", encoding="utf-8-sig", newline="\n")
    print(f"written: {len(VICTORIES)} victory screens")


if __name__ == "__main__":
    main()
