"""Generals, field marshals and admirals for every people (no game needed, ~1 s).

Run AFTER tools/world.py, tools/portraits.py and tools/army.py (it reads history/units for the size of each army and
fleet, portraits/00_portraits.txt for the culture's portraits, common/names for the names) and appends the
recruit_character lines to history/countries (world.py rewrites those files, so run this after every world.py).

  every country with an army:  1 general;  4+ divisions: 2 generals;  8+ divisions: + a field marshal;
  20+ divisions: 2 field marshals and 4 generals.  4+ ships: an admiral, 15+ ships: two.
Attested commanders of about 509-490 BC for the great powers are in NAMED; the rest get names from their people's list.

Writes common/characters/ante_commanders.txt and localisation/english/ante_commanders_l_english.yml.
"""
import hashlib
import random
import re
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
MARK = "# --- commanders (tools/commanders.py)"

# tag -> [(key, name, role, skill)]   role: fm = field marshal, gen = general, adm = admiral
NAMED = {
    "ROM": [("valerius", "Publius Valerius Publicola", "fm", 3), ("larcius", "Titus Larcius Flavus", "gen", 3),
            ("postumius", "Aulus Postumius Albus", "gen", 3), ("cocles", "Publius Horatius Cocles", "gen", 2),
            ("scaevola", "Gaius Mucius Scaevola", "gen", 2)],
    "CAR": [("hasdrubal", "Hasdrubal son of Mago", "fm", 3), ("malchus", "Malchus", "gen", 3),
            ("himilco", "Himilco the Navigator", "adm", 3), ("hanno", "Hanno the Navigator", "adm", 2)],
    "PRS": [("mardonius", "Mardonius", "fm", 4), ("megabazus", "Megabazus", "fm", 3), ("otanes", "Otanes", "gen", 3),
            ("artaphernes", "Artaphernes", "gen", 3), ("hydarnes", "Hydarnes", "gen", 3), ("daurises", "Daurises", "gen", 2),
            ("datis", "Datis the Mede", "adm", 3), ("megabates", "Megabates", "adm", 2)],
    "ATH": [("miltiades", "Miltiades", "fm", 4), ("callimachus", "Callimachus of Aphidnae", "gen", 3),
            ("aristides", "Aristides the Just", "gen", 3), ("themistocles", "Themistocles", "adm", 4)],
    "LAK": [("demaratus", "Demaratus", "fm", 3), ("dorieus", "Dorieus", "gen", 3), ("leonidas", "Leonidas", "gen", 4),
            ("eurybiades", "Eurybiades", "adm", 2)],
    "MKD": [("alexander", "Alexander son of Amyntas", "gen", 3)],
    "CLU": [("arruns", "Arruns Porsenna", "gen", 3)],
    "LAT": [("sextus", "Sextus Tarquinius", "gen", 2)],
    "SCY": [("scopasis", "Scopasis", "gen", 3), ("taxacis", "Taxacis", "gen", 3)],
    "KRO": [("philippos", "Philippos of Croton", "gen", 2)],
}
SKILLS = {  # (attack, defense, planning, logistics) by skill
    1: (1, 1, 1, 1), 2: (2, 2, 1, 2), 3: (3, 3, 2, 2), 4: (4, 3, 3, 3)}


def divisions(tag):
    p = MOD / "history" / "units" / f"{tag}_245.txt"
    return len(re.findall(r"^\s*division = \{", p.read_text(encoding="utf-8-sig"), re.M)) if p.exists() else 0


def ships(tag):
    p = MOD / "history" / "units" / f"{tag}_245_naval.txt"
    return len(re.findall(r"\bship = \{", p.read_text(encoding="utf-8-sig"))) if p.exists() else 0


def block(text, tag):
    m = re.search(rf"^{tag} = \{{", text, re.M)
    if not m:
        return ""
    depth, i = 0, m.end() - 1
    for j in range(i, len(text)):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        if depth == 0:
            return text[i:j]
    return ""


def words(text):
    return re.findall(r"[^\s{}\"]+", text)


def main():
    names_txt = (MOD / "common" / "names" / "ante_names.txt").read_text(encoding="utf-8-sig")
    port_txt = (MOD / "portraits" / "00_portraits.txt").read_text(encoding="utf-8-sig")
    chars, loc = ["# Generated by tools/commanders.py", "characters = {"], ["l_english:"]
    total = {"fm": 0, "gen": 0, "adm": 0}
    for fp in sorted((MOD / "history" / "countries").glob("*.txt")):
        tag = fp.name[:3]
        if tag == "WLD":
            continue
        d, s = divisions(tag), ships(tag)
        if d == 0 and s == 0:
            continue
        rnd = random.Random(int(hashlib.md5(tag.encode()).hexdigest()[:8], 16))
        nb = block(names_txt, tag)
        male = words(re.search(r"male = \{\s*names = \{([^}]*)\}", nb).group(1)) if "male" in nb else []
        sur_m = re.search(r"surnames = \{([^}]*)\}", nb)
        surnames = words(sur_m.group(1)) if sur_m else []
        pics = re.findall(r'"(GFX_ante_portrait_\w+)"', block(port_txt, tag).split("navy")[0])
        want = []
        if d:
            want += ["gen"] * (1 if d < 4 else 2 if d < 20 else 4) + ["fm"] * (0 if d < 8 else 1 if d < 20 else 2)
        if s >= 4:
            want += ["adm"] * (1 if s < 15 else 2)
        people = list(NAMED.get(tag, []))
        have = [r for *_, r, _ in people]
        used = {n for _, n, _, _ in people}
        for role in want:                       # fill up with generated commanders
            if role in have:
                have.remove(role)
                continue
            for _ in range(50):
                name = rnd.choice(male) if male else f"{tag} commander"
                if surnames and rnd.random() < 0.7:
                    name += " " + rnd.choice(surnames)
                if name not in used:
                    break
            used.add(name)
            people.append((f"g{len(people)}_" + re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_"), name, role, rnd.choice([1, 1, 2, 2, 3])))
        lines = []
        for i, (key, name, role, skill) in enumerate(people):
            cid = f"{tag}_cmd_{key}"
            a, de, pl, lo = SKILLS[skill]
            pic = pics[i % len(pics)] if pics else None
            out = [f"\t{cid} = {{", f"\t\tname = {cid}"]
            if pic:
                out.append(f'\t\tportraits = {{ army = {{ large = "{pic}" }} }}')
            if role == "adm":
                out += ["\t\tnavy_leader = {", "\t\t\ttraits = { }", f"\t\t\tskill = {skill}", f"\t\t\tattack_skill = {a}",
                        f"\t\t\tdefense_skill = {de}", f"\t\t\tmaneuvering_skill = {pl}", f"\t\t\tcoordination_skill = {lo}",
                        "\t\t\tlegacy_id = -1", "\t\t}"]
            else:
                out += ["\t\tfield_marshal = {" if role == "fm" else "\t\tcorps_commander = {", "\t\t\ttraits = { }",
                        f"\t\t\tskill = {skill}", f"\t\t\tattack_skill = {a}", f"\t\t\tdefense_skill = {de}",
                        f"\t\t\tplanning_skill = {pl}", f"\t\t\tlogistics_skill = {lo}", "\t\t\tlegacy_id = -1", "\t\t}"]
            out.append("\t}")
            chars += out
            loc.append(f' {cid}:0 "{name.replace(chr(34), chr(39))}"')
            lines.append(f"recruit_character = {cid}")
            total[role] += 1
        # append (idempotent) to the country history
        text = fp.read_text(encoding="utf-8-sig")
        text = text.split("\n" + MARK)[0].rstrip("\n")
        fp.write_text(text + "\n" + MARK + "\n" + "\n".join(lines) + "\n", encoding="utf-8-sig", newline="\n")
    chars.append("}")
    (MOD / "common" / "characters" / "ante_commanders.txt").write_text("\n".join(chars) + "\n", encoding="utf-8", newline="\n")
    (MOD / "localisation" / "english" / "ante_commanders_l_english.yml").write_text("\n".join(loc) + "\n",
                                                                                    encoding="utf-8-sig", newline="\n")
    print(f"written: {total['fm']} field marshals, {total['gen']} generals, {total['adm']} admirals")


if __name__ == "__main__":
    main()
