"""The world of 509 BC (245 AUC) outside Italy, Sicily, Sardinia, Corsica and Punic Africa.

Source of truth for tools/world.py. Italy and Carthage's heartland stay as they were built first
(tools/data/core_states_245.json, frozen from the first generator); everything else on the map is
described here: who lived where, with real longitudes and latitudes (tools/geo.py turns them into
map pixels).

C(tag, name, adjective, culture, government)            a people / state
R(tag, region name, lon, lat, population in thousands, ...)   a region it holds; the first R of a
    tag is its heartland and its first city the capital. Every land province goes to the region whose
    seed is nearest overland.
    city=   name of the main settlement at (lon, lat); defaults to the region name
    vp=     victory points of that settlement;  port=True  it has a harbour
    extra=  more settlements: (name, lon, lat, vp, port)
    seeds=  more (lon, lat) points that belong to the region (shapes big territories)
    power=  reach: below 1 the region stays small (city states), above 1 it spreads (empires, nomads)
WILD(name, (lon, lat), ...)   uninhabited or unknown land: impassable Terra Incognita

Names and borders follow Herodotus, Hecataeus and the archaeology of the late 6th century BC as far
as a game map allows; tribal names known only from later sources are used where nothing earlier exists.
Populations are orders of magnitude for the late 6th century BC (not the 5th-century peak), on the same
cautious yardstick as Italy's hand-made states (Rome and its land: 40 thousand).
"""

from data.world_245 import COUNTRIES as CORE_COUNTRIES   # Italy, Sicily, Sardinia, Corsica, Punic Africa

PEOPLES = {}       # tag -> dict(name, adj, culture, gov, color)
REGIONS = []       # dicts, in order
WILDS = []         # (name, [(lon, lat), ...])

# culture -> graphics, flag style, name list (tools/data/names_509bc.py), urban = builds cities
CULTURES = {
    "celtic":     dict(gfx="western_european", flag="celtic", names="celtic", urban=False),
    "iberian":    dict(gfx="western_european", flag="iberian", names="iberian", urban=False),
    "germanic":   dict(gfx="western_european", flag="germanic", names="germanic", urban=False),
    "northern":   dict(gfx="eastern_european", flag="northern", names="northern", urban=False),
    "greek":      dict(gfx="eastern_european", flag="greek", names="greek", urban=True),
    "illyrian":   dict(gfx="eastern_european", flag="illyrian", names="iapygian", urban=False),
    "thracian":   dict(gfx="eastern_european", flag="thracian", names="thracian", urban=False),
    "scythian":   dict(gfx="eastern_european", flag="steppe", names="scythian", urban=False),
    "caucasian":  dict(gfx="middle_eastern", flag="caucasian", names="caucasian", urban=False),
    "anatolian":  dict(gfx="middle_eastern", flag="anatolian", names="anatolian", urban=True),
    "persian":    dict(gfx="middle_eastern", flag="persian", names="persian", urban=True),
    "phoenician": dict(gfx="middle_eastern", flag="punic", names="punic", urban=True),
    "arabian":    dict(gfx="middle_eastern", flag="arabian", names="arabian", urban=False),
    "libyan":     dict(gfx="african", flag="tribal", names="libyan", urban=False),
    "nilotic":    dict(gfx="african", flag="nilotic", names="nilotic", urban=True),
    "african":    dict(gfx="african", flag="african", names="nilotic", urban=False),
}


def C(tag, name, adj, culture, gov, color=None):
    assert tag not in PEOPLES and tag not in CORE_COUNTRIES, tag
    assert len(tag) == 3 and tag.isupper(), tag
    assert culture in CULTURES, culture
    PEOPLES[tag] = dict(name=name, adj=adj, culture=culture, gov=gov, color=color)


def R(tag, name, lon, lat, pop, city=None, vp=1, port=False, extra=(), seeds=(), power=1.0):
    assert tag in PEOPLES or tag in CORE_COUNTRIES, tag      # Carthage also holds land outside its heartland
    REGIONS.append(dict(owner=tag, name=name, lon=lon, lat=lat, pop=pop * 1000, power=power,
                        cities=[(city or name, lon, lat, vp, port)] + list(extra), seeds=[(lon, lat)] + list(seeds)))


def WILD(name, *seeds):
    WILDS.append((name, list(seeds)))


