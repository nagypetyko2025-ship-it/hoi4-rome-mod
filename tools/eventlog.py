"""In-game event log (no game needed): writes common/on_actions/ante_eventlog_on_actions.txt.

Every line goes to the game's game.log as   ANTE|<date>|<kind>|<field>|...   (the `log` effect), and
tools/watch.py collects them into a session report. Kinds:
  start    player tag at the start            war      ROOT declares war on FROM
  peace    ROOT makes peace with FROM          cap      ROOT capitulates to FROM
  annex    ROOT annexes FROM                   puppet   FROM makes ROOT its puppet
  faction  ROOT joins / creates a faction      gov      ROOT changes government
  state    ROOT takes a state from FROM (only when a tree country or the player is involved)
  invade   naval invasion by ROOT              month    monthly figures of the tree countries and the player
  focus    a focus completed (written by tools/content.py into every completion_reward)
Kept small on purpose: state changes and the monthly figures only for the countries with a focus tree of their own
and the player.
"""
import sys
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

TREE_TAGS = ["ROM", "ATH", "LAK", "MKD", "PRS", "CAR", "SEN"]
WATCHED = "OR = { " + " ".join(f"tag = {t}" for t in TREE_TAGS) + " is_ai = no }"
D = "[GetDateText]"


def log(*fields):
    return 'log = "ANTE|' + D + "|" + "|".join(fields) + '"'


def block(name, effect, limit=None):
    eff = effect if not limit else f"if = {{ limit = {{ {limit} }}\n\t\t\t\t{effect}\n\t\t\t}}"
    return [f"\t{name} = {{", "\t\teffect = {", f"\t\t\t{eff}", "\t\t}", "\t}"]


def main():
    month = log("month", "[ROOT.GetTag]", "states=[?num_controlled_states]", "pp=[?political_power|0]",
                "stab=[?stability|%0]", "ws=[?has_war_support|%0]", "mp=[?manpower|0]", "div=[?num_divisions]",
                "fac=[?num_of_factories]", "realm=[?ante_realm_states]")
    rome = log("rome", "[ROOT.GetTag]", "discord=[?ROM_discord|0]", "hatred=[?ROM_hatred|0]")
    out = ["# Generated by tools/eventlog.py - event log lines for tools/watch.py (game.log, prefix ANTE|)",
           "on_actions = {",
           "\ton_startup = {", "\t\teffect = {",
           "\t\t\tevery_country = { limit = { is_ai = no } " + log("start", "[This.GetTag]", "[This.GetName]") + " }",
           "\t\t}", "\t}"]
    out += block("on_declare_war", log("war", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_peace", log("peace", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_capitulation", log("cap", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_annex", log("annex", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_puppet", log("puppet", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_join_faction", log("faction", "[ROOT.GetTag]", "[FROM.GetTag]"))
    out += block("on_create_faction", log("faction", "[ROOT.GetTag]", "new"))
    out += block("on_government_change", log("gov", "[ROOT.GetTag]", "[ROOT.GetRulingIdeology]"))
    out += block("on_naval_invasion", log("invade", "[ROOT.GetTag]"))
    out += block("on_state_control_changed", log("state", "[ROOT.GetTag]", "[FROM.GetTag]", "[FROM.FROM.GetName]"),
                 limit=f"OR = {{ {WATCHED} FROM = {{ {WATCHED} }} }}")
    out += block("on_monthly", month + ("\n\t\t\t\tif = { limit = { tag = ROM } " + rome + " }"), limit=WATCHED)
    out.append("}")
    p = MOD / "common" / "on_actions" / "ante_eventlog_on_actions.txt"
    p.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"written: {p.relative_to(MOD)}")


if __name__ == "__main__":
    main()
