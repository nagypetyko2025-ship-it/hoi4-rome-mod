def wargoals():
    """the game's wargoal types with Terra Incognita (WLD) excluded as a target: nobody can justify a war goal on
    the empty land, so nobody can declare war on it. PREV is the target (the game's own comment), THIS is checked too."""
    import army
    src = (army.game_dir() / "common" / "wargoals" / "00_invasion.txt").read_text(encoding="utf-8-sig")
    out, n = [], 0
    for line in src.split("\n"):
        out.append(line)
        if line.strip().startswith("allowed = {") and line.strip().endswith("{"):
            out += ["\t\t\tNOT = { tag = WLD }   # Ante Imperium: Terra Incognita cannot be attacked",
                    "\t\t\tPREV = { NOT = { tag = WLD } }"]
            n += 1
    p = MOD / "common" / "wargoals" / "00_invasion.txt"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# Generated by tools/ai.py from the game's file (Terra Incognita cannot be a target)\n" + "\n".join(out),
                 encoding="utf-8", newline="\n")
    return n


def main():
    print(f"wargoals: {wargoals()} types closed against Terra Incognita")
    for rel, text in (("common/ai_templates/ante_templates.txt", TEMPLATES),
                      ("common/ai_strategy/ante_default.txt", STRATEGY),
                      ("common/on_actions/ante_ai_on_actions.txt", ON_ACTIONS)):
        p = MOD / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print("written: AI templates (infantry, cavalry), strategies, monthly ambition")


if __name__ == "__main__":
    main()
